# Numerical diagnostics only; no benchmark settings are selected from test scores.
source('scripts/paths.R');source('environment/preflight.R')
library(glma)
out<-file.path(output_dir(),'20261121-glma-gaussian-audit')
rows<-list()
for(case in c('maize','cattle')) {
  input<-readRDS(file.path(data_dir(),'prepared',paste0(case,'-gpbench.rds')))
  folds<-readRDS(file.path(output_dir(),case,'20261121-glma-mkl','folds.rds'))
  train<-which(folds$fold!=1L);test<-which(folds$fold==1L)
  y<-input$Y[,if(case=='maize')'DTT'else'mkg']
  y[is.na(y)]<-mean(y,na.rm=TRUE)
  fit<-glma::glma_full_marker_prediction(
    file.path(output_dir(),case,'20261121-glma-mkl','anonymous-dosages.bed'),
    nrow(input$X),ncol(input$X),train,y[train],'infinitesimal',threads=4L)
  Xtr<-input$X[train,,drop=FALSE]
  native_prediction<-as.numeric(fit$intercept+input$X[test,,drop=FALSE]%*%fit$effects)
  original<-read.csv(file.path(output_dir(),case,'20261121-glma-mkl','predictions.csv'))
  original<-original[original$method=='glma_infinitesimal',]
  stopifnot(max(abs(native_prediction-original$predicted[match(input$ids[test],original$id)]))<1e-7)
  residual<-as.numeric(y[train]-fit$intercept-Xtr%*%fit$effects)
  beta_std<-fit$effects*fit$scales
  lambda<-ncol(Xtr)*fit$residual_variance/fit$genetic_variance
  score<-as.numeric((crossprod(Xtr,residual)-fit$centers*sum(residual))/fit$scales-lambda*beta_std)
  rhs<-as.numeric(crossprod(Xtr,y[train]-mean(y[train]))/fit$scales)
  center<-fit$initial_genetic_variance/(fit$initial_genetic_variance+fit$initial_residual_variance)
  grid<-center*c(.5,.75,1)
  summary<-data.frame(dataset=paste0('gpbench_',case),fold=1L,
    initial_ratio=center,final_ratio=fit$genetic_variance/(fit$genetic_variance+fit$residual_variance),
    used_initial_without_bracket=fit$grid_used_initial,
    grid=paste(signif(grid,7),collapse=';'),
    mc_equations=paste(signif(fit$grid_equations,7),collapse=';'),
    normal_equation_relative_residual=sqrt(sum(score^2))/sqrt(sum(rhs^2)),
    intercept_residual_mean=mean(residual),refit_sweeps=fit$sweeps,
    native_refit_accepted=fit$converged,
    objective_history_length=length(fit$refit_objective_history))
  if(case=='maize') {
    # Independent fixed-V Cholesky reference in centered standardized coordinates.
    scaled<-sweep(input$X,2,fit$scales,'/')
    Kall<-tcrossprod(scaled)/ncol(scaled)
    K<-Kall[train,train,drop=FALSE];Kt<-Kall[test,train,drop=FALSE]
    mu<-rowMeans(K);grand<-mean(K)
    Kc<-sweep(sweep(K,1,mu,'-'),2,mu,'-')+grand
    Ktc<-sweep(sweep(Kt,1,rowMeans(Kt),'-'),2,mu,'-')+grand
    V<-fit$genetic_variance*Kc+diag(fit$residual_variance,length(train))
    factor<-chol(V)
    Py<-backsolve(factor,forwardsolve(t(factor),y[train]-mean(y[train])))
    exact<-as.numeric(mean(y[train])+fit$genetic_variance*Ktc%*%Py)
    owned<-readRDS(file.path(out,'maize-1-glma_variances_exact_solve.rds'))$predicted
    stopifnot(max(abs(exact-owned))<1e-7)
    summary$independent_cholesky_vs_owned_max<-max(abs(exact-owned))
    summary$native_vs_exact_prediction_rms<-sqrt(mean((native_prediction-exact)^2))
    eig<-eigen(Kc,symmetric=TRUE)
    d<-head(eig$values,-1);a<-as.numeric(crossprod(eig$vectors[,seq_along(d)],y[train]-mean(y[train])))
    profile<-function(h) {
      v<-1-h+h*d;q<-sum(a*a/v);df<-length(a);s<-q/df
      c(log_likelihood=-.5*(df*(log(2*pi)+1+log(s))+sum(log(v))+log(length(train))),
        score_h=.5*(sum(a*a*(d-1)/(v*v))/s-sum((d-1)/v)),profile_scale=s)
    }
    reference<-readRDS(file.path(out,'maize-1-standardized_reml.rds'))$fit$parameters
    values<-sapply(c(grid,reference['genetic']/sum(reference)),profile)
    write.csv(data.frame(ratio=c(grid,reference['genetic']/sum(reference)),t(values)),
      file.path(out,'maize-fold1-exact-profile.csv'),row.names=FALSE)
    summary$exact_profile_scores_at_grid<-paste(signif(values['score_h',1:3],7),collapse=';')
    summary$profile_loglik_gain_reml_vs_native_ratio<-values['log_likelihood',4]-values['log_likelihood',3]
    rm(scaled,Kall,K,Kt,Kc,Ktc,V,factor,eig);gc()
  } else {
    summary$independent_cholesky_vs_owned_max<-NA_real_
    summary$native_vs_exact_prediction_rms<-sqrt(mean((native_prediction-
      readRDS(file.path(out,'cattle-1-glma_variances_exact_solve.rds'))$predicted)^2))
    summary$exact_profile_scores_at_grid<-NA_character_
    summary$profile_loglik_gain_reml_vs_native_ratio<-NA_real_
  }
  rows[[case]]<-summary
  saveRDS(fit,file.path(out,paste0(case,'-fold1-native-grid-diagnostics.rds')))
  write.csv(do.call(rbind,rows),file.path(out,'native-diagnostics.csv'),row.names=FALSE)
  print(summary,row.names=FALSE)
  rm(input,Xtr,fit);gc()
}
