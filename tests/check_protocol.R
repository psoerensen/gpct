stopifnot(a[['predictive_ability']]==1,a[['rmse']]==0,a[['predictive_r_squared']]==1)
b <- metrics(c(1,2,4),c(2,2,2))
stopifnot(is.na(b[['predictive_ability']]),abs(b[['predictive_r_squared']]+1/14)<1e-12)
stopifnot(metrics(rep(1,3),rep(2,3))[['predictive_r_squared']]==0,
          metrics(rep(1,3),rep(1,3))[['predictive_r_squared']]==1)
r <- gpbench_response(c(1,3,NA_real_))
stopifnot(identical(r$y,c(1,3,2)),identical(r$imputed,c(FALSE,FALSE,TRUE)))
path <- paste0(tempfile(),'.csv'); ids <- paste0('row-',1:23)
folds <- saved_folds(ids,path)
stopifnot(nrow(folds)==23L,max(tabulate(folds$fold))-min(tabulate(folds$fold))<=1L,
          identical(folds,saved_folds(ids,path)))
bad <- read.csv(path);bad$source_row[1]<-999L;write.csv(bad,path,row.names=FALSE)
stopifnot(inherits(try(saved_folds(ids,path),silent=TRUE),'try-error'))
unlink(c(path,sub('\\.csv$','.json',path)))
